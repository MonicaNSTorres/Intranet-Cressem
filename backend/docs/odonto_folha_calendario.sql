CREATE TABLE DBACRESSEM.ODONTO_FOLHA_CALENDARIO (
  ID_ODONTO_FOLHA_CALENDARIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CD_COMPETENCIA_CORTE VARCHAR2(7) NOT NULL,
  ID_EMPRESA NUMBER NOT NULL,
  DT_CORTE DATE NOT NULL,
  DT_CORTE_EFETIVO DATE NOT NULL,
  DT_ENVIO_AVISO DATE NOT NULL,
  DT_ENVIO_AVISO_EFETIVO DATE NOT NULL,
  ST_FECHAMENTO VARCHAR2(20) DEFAULT 'ABERTO' NOT NULL,
  DT_FECHAMENTO DATE,
  DS_ERRO_FECHAMENTO VARCHAR2(2000),
  ST_AVISO VARCHAR2(20) DEFAULT 'PENDENTE' NOT NULL,
  NR_TENTATIVAS_AVISO NUMBER DEFAULT 0 NOT NULL,
  DT_AVISO_ENVIADO DATE,
  DS_ERRO_AVISO VARCHAR2(2000),
  DT_CRIACAO DATE DEFAULT SYSDATE NOT NULL,
  DT_ATUALIZACAO DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT UX_ODONTO_FOLHA_CAL_EMP_COMP UNIQUE (CD_COMPETENCIA_CORTE, ID_EMPRESA),
  CONSTRAINT FK_ODONTO_FOLHA_CAL_EMP FOREIGN KEY (ID_EMPRESA) REFERENCES DBACRESSEM.ODONTO_EMPRESA (ID_EMPRESA),
  CONSTRAINT CK_ODONTO_FOLHA_CAL_FECH CHECK (ST_FECHAMENTO IN ('ABERTO', 'FECHADO', 'ERRO')),
  CONSTRAINT CK_ODONTO_FOLHA_CAL_AVISO CHECK (ST_AVISO IN ('PENDENTE', 'ENVIADO', 'FALHA'))
);

ALTER TABLE DBACRESSEM.ODONTO_FOLHA_ENVIO DROP CONSTRAINT CK_ODONTO_FOLHA_STATUS;
ALTER TABLE DBACRESSEM.ODONTO_FOLHA_ENVIO ADD CONSTRAINT CK_ODONTO_FOLHA_STATUS CHECK (ST_ENVIO IN ('FECHADO', 'PROCESSANDO', 'ENVIADO', 'FALHA'));
