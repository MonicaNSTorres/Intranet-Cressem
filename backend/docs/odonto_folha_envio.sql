-- Execute somente quando as tabelas ainda não existirem no schema DBACRESSEM.
-- Em ambientes onde elas já existem, a rotina usa exatamente esta nomenclatura.
CREATE TABLE DBACRESSEM.ODONTO_FOLHA_ENVIO (
  ID_ODONTO_FOLHA_ENVIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CD_COMPETENCIA VARCHAR2(7) NOT NULL,
  DT_REFERENCIA DATE NOT NULL,
  ID_EMPRESA NUMBER NOT NULL,
  NM_EMPRESA VARCHAR2(150) NOT NULL,
  DS_DESTINATARIO VARCHAR2(1000) NOT NULL,
  NM_ARQUIVO VARCHAR2(255) NOT NULL,
  NR_REGISTROS NUMBER NOT NULL,
  VL_TOTAL NUMBER(15,2) NOT NULL,
  ST_ENVIO VARCHAR2(20) NOT NULL,
  NR_TENTATIVAS NUMBER DEFAULT 0 NOT NULL,
  DT_CRIACAO DATE DEFAULT SYSDATE NOT NULL,
  DT_ENVIO DATE,
  DS_ERRO VARCHAR2(2000),
  CONSTRAINT UX_ODONTO_FOLHA_COMPETENCIA_EMPRESA UNIQUE (CD_COMPETENCIA, ID_EMPRESA),
  CONSTRAINT CK_ODONTO_FOLHA_STATUS CHECK (ST_ENVIO IN ('PROCESSANDO', 'ENVIADO', 'FALHA')),
  CONSTRAINT CK_ODONTO_FOLHA_TENTATIVAS CHECK (NR_TENTATIVAS >= 0),
  CONSTRAINT CK_ODONTO_FOLHA_VALOR CHECK (VL_TOTAL >= 0),
  CONSTRAINT FK_ODONTO_FOLHA_EMPRESA FOREIGN KEY (ID_EMPRESA) REFERENCES DBACRESSEM.ODONTO_EMPRESA (ID_EMPRESA)
);

CREATE TABLE DBACRESSEM.ODONTO_FOLHA_ENVIO_ITEM (
  ID_ODONTO_FOLHA_ENVIO_ITEM NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_ODONTO_FOLHA_ENVIO NUMBER NOT NULL,
  NR_ORDEM NUMBER NOT NULL,
  ID_TITULAR NUMBER NOT NULL,
  ID_OPERADORA NUMBER NOT NULL,
  NR_CPF_TITULAR VARCHAR2(11) NOT NULL,
  NM_TITULAR VARCHAR2(150) NOT NULL,
  NR_MATRICULA VARCHAR2(50),
  NM_EMPRESA VARCHAR2(150),
  NR_CNPJ_EMPRESA VARCHAR2(14),
  NM_OPERADORA VARCHAR2(150) NOT NULL,
  DS_PLANOS VARCHAR2(1000) NOT NULL,
  QT_BENEFICIARIOS NUMBER NOT NULL,
  VL_TOTAL NUMBER(15,2) NOT NULL,
  DT_CRIACAO DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT UX_ODONTO_FOLHA_ITEM_ORDEM UNIQUE (ID_ODONTO_FOLHA_ENVIO, NR_ORDEM),
  CONSTRAINT FK_ODONTO_FOLHA_ITEM_ENVIO FOREIGN KEY (ID_ODONTO_FOLHA_ENVIO) REFERENCES DBACRESSEM.ODONTO_FOLHA_ENVIO (ID_ODONTO_FOLHA_ENVIO),
  CONSTRAINT CK_ODONTO_FOLHA_ITEM_QTDE CHECK (QT_BENEFICIARIOS >= 0),
  CONSTRAINT CK_ODONTO_FOLHA_ITEM_VALOR CHECK (VL_TOTAL >= 0)
);
